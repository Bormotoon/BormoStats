export const percentMetrics = new Set([4,6,8,12,17,22,25,31,34,35,36,41,42,43,47,48]);
const displayNumber = n => new Intl.NumberFormat("ru-RU", {maximumFractionDigits:1}).format(n);
export const formatMetric = (value,index) => value == null ? "—" : percentMetrics.has(index) ? `${displayNumber(value*100)}%` : displayNumber(value);
